--
-- 이 프로젝트에는 구조를 시험하려고 넣은 가짜 이름들이 남아 있다.
--   기기 10건  : GEN-1, MTR-1A, CEP-1A, CWP-1A, FWP-1A, GIS-154-1 …
--   조작대상 22건: CB-154-1A, CB-6.9-FWP1A, GCB-1, DS-13.8-GEN1-1 …
--
-- 그대로 두면 "조작대상 찾기" 에서 실제 설비와 섞여 나온다. 확정 시드가
-- 이것들을 대체하므로 지우는 것이 맞지만, 되돌릴 수 없으니 설정 스크립트
-- (redtag-01)에서 빼 두었다. 확인한 뒤 따로 실행한다.
--
-- 실행 시점: 01~06 을 끝낸 뒤 아무 때나. 시드와 id 가 겹치지 않아
--            먼저 실행하든 나중에 하든 결과가 같다.
